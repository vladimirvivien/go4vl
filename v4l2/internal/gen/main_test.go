package main

import (
	"strings"
	"testing"
)

func TestFormatTypes(t *testing.T) {
	raw := []byte(`// Code generated by cmd/cgo -godefs; DO NOT EDIT.
// cgo -godefs defs_types.go

package v4l2

const (
	cVIDIOC_QUERYCAP uintptr = 0x80685600
	cVIDIOC_QBUF     uintptr = 0xc058560f
)

type cMediaEntityDesc struct {
	Id  uint32
	Dev _Ctype_struct___2
}

type cV4L2BTTimings struct {
	Width      uint32
	Pixelclock uint64
}

type cV4L2DecoderCmd struct {
	Cmd  uint32
	Stop _Ctype_struct___0
}

type cV4L2EncoderCmd struct {
	Cmd uint32
	Raw _Ctype_struct___1
}
`)

	formatted, err := formatTypes(raw, "arm64")
	if err != nil {
		t.Fatalf("formatTypes() error = %v", err)
	}

	got := string(formatted)
	for _, want := range []string{
		"// Code generated by go generate ./v4l2; DO NOT EDIT.\n",
		"//go:build linux && arm64\n",
		"Stop [8]byte",
		"Raw [8]uint32",
		"Dev [2]uint32",
		"Pixelclock [8]byte",
	} {
		if !strings.Contains(got, want) {
			t.Errorf("formatTypes() missing %q:\n%s", want, got)
		}
	}
	for _, unwanted := range []string{"cmd/cgo", "// cgo -godefs"} {
		if strings.Contains(got, unwanted) {
			t.Errorf("formatTypes() unexpectedly contains %q:\n%s", unwanted, got)
		}
	}
}

func TestFormatTypesUnresolvedCtype(t *testing.T) {
	raw := []byte(`package v4l2

type cUnknown struct {
	Field _Ctype_struct___9
}
`)
	if _, err := formatTypes(raw, "amd64"); err == nil {
		t.Fatal("expected error for unresolved _Ctype_ reference")
	}
}

func TestResolveCCCrossRequiresEnv(t *testing.T) {
	t.Setenv("CC", "")
	if _, err := resolveCC("arm64", "amd64"); err == nil || !strings.Contains(err.Error(), "CC=") {
		t.Fatalf("resolveCC(cross without CC) = %v, want error mentioning CC=", err)
	}

	t.Setenv("CC", "aarch64-linux-gnu-gcc")
	cc, err := resolveCC("arm64", "amd64")
	if err != nil || cc != "aarch64-linux-gnu-gcc" {
		t.Fatalf("resolveCC(cross with CC) = (%q, %v), want aarch64-linux-gnu-gcc", cc, err)
	}
}
